// Bundles the harness (src/harness/index.ts and what it imports) into one CommonJS file that the composite action's
// github-script step requires. The bundle is committed, because an action runs from the repository as checked out:
// there is no install step. CI fails if it is stale (`npm run build` then `git diff --exit-code harness/dist`).
import { build } from 'esbuild'

await build({
  entryPoints: ['src/harness/index.ts'],
  outfile: 'harness/dist/index.cjs',
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node22',
  external: ['node:*'],
  legalComments: 'none',
  minify: true,
  sourcemap: false,
  banner: { js: '// Generated by scripts/bundle-harness.mjs from src/harness. Do not edit.' },
  logLevel: 'warning',
})
