// Bundles the harness (src/harness/index.ts and what it imports) into one CommonJS file that the composite action's
// github-script step requires. The bundle is committed, because an action runs from the repository as checked out:
// there is no install step. CI fails if it is stale (`npm run build` then `git diff --exit-code harness/dist`).
import { build } from 'esbuild'

// the GitHub action's bundle, and the GitLab pipeline job's (src/harness/gitlab.ts: the same tasks, GitLab answering)
for (const [entry, outfile] of [['src/harness/index.ts', 'harness/dist/index.cjs'], ['src/harness/gitlab-main.ts', 'harness/dist/gitlab.cjs']]) await build({
  entryPoints: [entry],
  outfile,
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node22',
  external: ['node:*'],
  legalComments: 'none',
  minify: true,
  sourcemap: false,
  banner: { js: '// Generated by scripts/bundle-harness.mjs from src/harness. Do not edit.' },
  logLevel: 'warning',
})
