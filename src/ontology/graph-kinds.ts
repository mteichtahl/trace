/**
 * The graph view's kinds of item, made from the ontology (plan P6.3): each class the view draws names its kind with
 * trace:graphKind, so the API (src/api/actions-graph.ts) and the app (web/src/lib/graph.ts) read one generated list
 * instead of each keeping its own. scripts/graph-kinds.mjs writes it to src/ontology/graph-kinds.gen.ts and
 * web/src/lib/graph-kinds.gen.ts; test/api/graph-vocabulary.test.ts fails while either differs from the ontology.
 *
 *   ORDER     the order the view lists kinds in: the design from intent to board, the evidence, the record's
 *             decisions, then memory, documents and people. A kind a class names must be here
 *   APP_ONLY  kinds no class of the ontology stores, with why: the view draws them from elsewhere
 */
import type { Vocabulary } from './vocab.js'

export const ORDER = [
  'intent', 'requirement', 'block', 'part', 'datasheet', 'component', 'net', 'case', 'run', 'artifact', 'gate', 'criterion', 'waiver', 'decision',
  'memory', 'document', 'person',
] as const

export const APP_ONLY: Readonly<Record<string, string>> = {
  datasheet: 'a page of a part\'s datasheet: the record keeps no link from a part to its pages yet',
  memory: 'the agents\' long-term memory, kept outside the project\'s records',
}

export interface GraphKinds { nodeKinds: string[]; classKinds: Record<string, string> }

/** The kinds from the ontology's graphKind annotations, in ORDER, with the app's own. Throws on a kind not in ORDER. */
export function graphKinds(v: Vocabulary): GraphKinds {
  const classKinds: Record<string, string> = {}
  for (const c of [...v.classes.values()].sort((a, b) => a.name.localeCompare(b.name))) if (c.graphKind) classKinds[c.name] = c.graphKind
  const named = new Set([...Object.values(classKinds), ...Object.keys(APP_ONLY)])
  const unknown = [...named].filter((k) => !(ORDER as readonly string[]).includes(k))
  if (unknown.length) throw new Error(`graph kinds not in ORDER (src/ontology/graph-kinds.ts): ${unknown.join(', ')}`)
  return { nodeKinds: ORDER.filter((k) => named.has(k)), classKinds }
}

/** The generated module's text. */
export function renderGraphKinds(k: GraphKinds): string {
  return [
    '// Generated by scripts/graph-kinds.mjs from the ontology (trace:graphKind; src/ontology/graph-kinds.ts). Do not edit.',
    '',
    '/** The kinds of item the graph view draws, in the order it lists them. */',
    `export const NODE_KINDS = [${k.nodeKinds.map((x) => `'${x}'`).join(', ')}] as const`,
    '',
    '/** The kind each class of the ontology is drawn as. */',
    'export const CLASS_KINDS: Readonly<Record<string, (typeof NODE_KINDS)[number]>> = {',
    ...Object.entries(k.classKinds).map(([c, kind]) => `  ${c}: '${kind}',`),
    '}',
    '',
  ].join('\n')
}
