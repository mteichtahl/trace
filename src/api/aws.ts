/**
 * The AWS calls the API runtime makes, behind small interfaces so tests run offline:
 *
 *   Cognito       AdminGetUser, ListUsers, ListUsersInGroup, AdminCreateUser, AdminListGroupsForUser,
 *                 AdminAddUserToGroup, AdminRemoveUserFromGroup, AdminUserGlobalSignOut — the JSON protocol, signed
 *                 with SigV4 here (the Cognito SDK client is not a dependency; credentials come from the runtime role
 *                 via the SDK chain); for connected systems (docs/external-access.md): CreateUserPoolClient,
 *                 UpdateUserPoolClient, DeleteUserPoolClient, AddUserPoolClientSecret, DeleteUserPoolClientSecret,
 *                 ListUserPoolClientSecrets. A client secret is returned to the caller and never logged here.
 *                 Those six touch only a connected system's own client (a backstop under services.*'s admin check,
 *                 so a bug there can never reach the people's CLI or web client): a new client must be named
 *                 <prefix>-svc-<name>, and every other call must name a client that is a connected system in the
 *                 access store (and an update must keep the name its record gives). The one exception: a client this
 *                 process just made may be deleted again before its record exists (services.create undoing itself)
 *   Secrets       the GitHub token (TRACE_GITHUB_SECRET_ARN), cached for 10 minutes
 */
import { createHash, createHmac } from 'node:crypto'
import { z } from 'zod'

// ------------------------------------------------------------------ SigV4 (POST, JSON body, no query string)

export interface Credentials { accessKeyId: string; secretAccessKey: string; sessionToken?: string | undefined }

const sha256 = (s: string): string => createHash('sha256').update(s).digest('hex')
const hmac = (k: Buffer | string, s: string): Buffer => createHmac('sha256', k).update(s).digest()

export function signV4(o: { host: string; region: string; service: string; body: string; headers: Record<string, string>; creds: Credentials; now?: Date }): Record<string, string> {
  const t = (o.now ?? new Date()).toISOString().replace(/[-:]/g, '').replace(/\.\d{3}/, '')
  const day = t.slice(0, 8)
  const headers: Record<string, string> = { ...Object.fromEntries(Object.entries(o.headers).map(([k, v]) => [k.toLowerCase(), v.trim()])), host: o.host, 'x-amz-date': t }
  if (o.creds.sessionToken) headers['x-amz-security-token'] = o.creds.sessionToken
  const names = Object.keys(headers).sort()
  const canonical = ['POST', '/', '', ...names.map((n) => `${n}:${headers[n] ?? ''}`), '', names.join(';'), sha256(o.body)].join('\n')
  const scope = `${day}/${o.region}/${o.service}/aws4_request`
  const toSign = ['AWS4-HMAC-SHA256', t, scope, sha256(canonical)].join('\n')
  const key = hmac(hmac(hmac(hmac(`AWS4${o.creds.secretAccessKey}`, day), o.region), o.service), 'aws4_request')
  const sig = createHmac('sha256', key).update(toSign).digest('hex')
  headers.authorization = `AWS4-HMAC-SHA256 Credential=${o.creds.accessKeyId}/${scope}, SignedHeaders=${names.join(';')}, Signature=${sig}`
  delete headers.host
  return headers
}

async function defaultCredentials(): Promise<Credentials> {
  const { fromNodeProviderChain } = await import('@aws-sdk/credential-providers')
  const c = await fromNodeProviderChain()()
  return { accessKeyId: c.accessKeyId, secretAccessKey: c.secretAccessKey, sessionToken: c.sessionToken }
}

// ------------------------------------------------------------------ Cognito

export interface CognitoUser { sub: string; username: string; email: string | null; status: string | null; enabled: boolean; name?: string | null | undefined }

export interface CognitoAdmin {
  getUser(username: string): Promise<CognitoUser | null>
  /** A person by email or sub (ListUsers with a filter), or null. */
  find(who: string): Promise<CognitoUser | null>
  listUsers(): Promise<CognitoUser[]>
  usersInGroup(group: string): Promise<CognitoUser[]>
  createUser(email: string): Promise<CognitoUser>
  groupsFor(username: string): Promise<string[]>
  addToGroup(username: string, group: string): Promise<void>
  removeFromGroup(username: string, group: string): Promise<void>
  /** AdminUserGlobalSignOut: every refresh token of the person is revoked (their access tokens run out within the hour). */
  signOut(username: string): Promise<void>
  /** A connected system's app client (client credentials only, with a secret): its id and its first secret. */
  createServiceClient(c: ServiceClientConfig): Promise<{ clientId: string; secret: string }>
  /** Set the app client's whole configuration (UpdateUserPoolClient resets whatever is left out). */
  updateServiceClient(clientId: string, c: ServiceClientConfig): Promise<void>
  /** Delete the app client; false when it was already gone. */
  deleteServiceClient(clientId: string): Promise<boolean>
  /** A second secret, generated by Cognito (an app client holds at most two). */
  addClientSecret(clientId: string): Promise<ClientSecret & { secret: string }>
  deleteClientSecret(clientId: string, secretId: string): Promise<void>
  /** The app client's secrets, by id and date: never their values. */
  listClientSecrets(clientId: string): Promise<ClientSecret[]>
}

/** What a connected system's app client is: everything else is fixed (client credentials, one-hour access tokens). */
export interface ServiceClientConfig { clientName: string; scopes: readonly string[] }
export interface ClientSecret { secretId: string; createdAt: string | null }

/** The full app client configuration for a connected system, sent whole on create and on every update. */
export function serviceClientBody(c: ServiceClientConfig): Record<string, unknown> {
  return {
    ClientName: c.clientName,
    AllowedOAuthFlows: ['client_credentials'],
    AllowedOAuthFlowsUserPoolClient: true,
    AllowedOAuthScopes: [...c.scopes],
    AccessTokenValidity: 60,
    TokenValidityUnits: { AccessToken: 'minutes', IdToken: 'minutes', RefreshToken: 'days' },
    // no person signs in through a system's client: only refresh (which client credentials never uses) is left on
    ExplicitAuthFlows: ['ALLOW_REFRESH_TOKEN_AUTH'],
    PreventUserExistenceErrors: 'ENABLED',
    EnableTokenRevocation: true,
  }
}

const SecretShape = z.object({ ClientSecretId: z.string(), ClientSecretCreateDate: z.number().optional() }).loose()
const toSecret = (s: z.output<typeof SecretShape>): ClientSecret => ({
  secretId: s.ClientSecretId, createdAt: s.ClientSecretCreateDate === undefined ? null : new Date(s.ClientSecretCreateDate * 1000).toISOString(),
})

const Attr = z.object({ Name: z.string(), Value: z.string().optional() }).loose()
const UserShape = z.object({
  Username: z.string(),
  Attributes: z.array(Attr).optional(),
  UserAttributes: z.array(Attr).optional(),
  UserStatus: z.string().optional(),
  Enabled: z.boolean().optional(),
}).loose()

function toUser(u: z.output<typeof UserShape>): CognitoUser {
  const attrs = u.Attributes ?? u.UserAttributes ?? []
  const at = (n: string): string | null => attrs.find((a) => a.Name === n)?.Value ?? null
  return { sub: at('sub') ?? u.Username, username: u.Username, email: at('email'), status: u.UserStatus ?? null, enabled: u.Enabled ?? true, name: at('name') }
}

export class CognitoError extends Error {
  override name = 'CognitoError'
  constructor(readonly type: string, message: string) { super(message) }
}

/** A connected system's app client name: <prefix>-svc-<name>, the name as access.ts ServiceName allows it. */
export const serviceClientName = (prefix: string, name: string): string => `${prefix}-svc-${name}`
const SERVICE_NAME = /^[a-z][a-z0-9-]{1,39}$/

/** Refused by the backstop: not a connected system's client. Never sent to Cognito. */
export class NotAServiceClient extends CognitoError {
  constructor(message: string) { super('NotAServiceClient', message) }
}

export interface HttpCognitoOptions {
  region: string
  poolId: string
  credentials?: () => Promise<Credentials>
  fetch?: typeof fetch
  /** the installation's prefix: connected systems' clients are <prefix>-svc-<name> (TRACE_PREFIX, default trace) */
  prefix?: string
  /** the connected system with this client id in the access store, or null (default: access.ts getService) */
  service?: (clientId: string) => Promise<{ name: string } | null>
}

export class HttpCognito implements CognitoAdmin {
  /** the clients this process made and has not deleted: services.create may undo one before its record exists */
  private readonly made = new Set<string>()
  constructor(private readonly o: HttpCognitoOptions) {}

  private get prefix(): string { return this.o.prefix || 'trace' }

  /** A new client's name must be <prefix>-svc-<name>. */
  private checkNewName(clientName: string): void {
    const pre = serviceClientName(this.prefix, '')
    if (!clientName.startsWith(pre) || !SERVICE_NAME.test(clientName.slice(pre.length))) {
      throw new NotAServiceClient(`refusing to make an app client named ${JSON.stringify(clientName)}: a connected system's is ${pre}<name>`)
    }
  }

  /** The client must be a connected system's: in the access store, with a name that makes <prefix>-svc-<name>. */
  private async checkService(clientId: string, clientName?: string): Promise<void> {
    const lookup = this.o.service ?? (async (id: string) => (await import('../core/access.js')).getService(id))
    const s = await lookup(clientId)
    if (!s) throw new NotAServiceClient(`refusing: app client ${clientId} is not a connected system`)
    if (!SERVICE_NAME.test(s.name)) throw new NotAServiceClient(`refusing: connected system ${JSON.stringify(s.name)} has a name trace would not give a system`)
    const want = serviceClientName(this.prefix, s.name)
    if (clientName !== undefined && clientName !== want) throw new NotAServiceClient(`refusing to rename app client ${clientId} to ${JSON.stringify(clientName)}: its record makes it ${want}`)
  }

  private async call(op: string, body: Record<string, unknown>): Promise<unknown> {
    const host = `cognito-idp.${this.o.region}.amazonaws.com`
    const text = JSON.stringify({ UserPoolId: this.o.poolId, ...body })
    const headers = signV4({
      host, region: this.o.region, service: 'cognito-idp', body: text,
      headers: { 'content-type': 'application/x-amz-json-1.1', 'x-amz-target': `AWSCognitoIdentityProviderService.${op}` },
      creds: await (this.o.credentials ?? defaultCredentials)(),
    })
    const r = await (this.o.fetch ?? fetch)(`https://${host}/`, { method: 'POST', headers, body: text, signal: AbortSignal.timeout(15_000) })
    const json: unknown = await r.json().catch(() => ({}))
    if (!r.ok) {
      const e = z.object({ __type: z.string().optional(), message: z.string().optional() }).loose().safeParse(json)
      const type = (e.success ? e.data.__type : undefined)?.split('#').at(-1) ?? `HTTP${r.status}`
      throw new CognitoError(type, `Cognito ${op}: ${type}${e.success && e.data.message ? `: ${e.data.message}` : ''}`)
    }
    return json
  }

  async getUser(username: string): Promise<CognitoUser | null> {
    try {
      return toUser(UserShape.parse(await this.call('AdminGetUser', { Username: username })))
    } catch (e) {
      if (e instanceof CognitoError && e.type === 'UserNotFoundException') return null
      throw e
    }
  }

  private async paged(op: string, extra: Record<string, unknown>, tokenKey: 'PaginationToken' | 'NextToken'): Promise<CognitoUser[]> {
    const out: CognitoUser[] = []
    let token: string | undefined
    const Page = z.object({ Users: z.array(UserShape).optional(), PaginationToken: z.string().optional(), NextToken: z.string().optional() }).loose()
    for (let i = 0; i < 100; i++) {
      const p = Page.parse(await this.call(op, { ...extra, Limit: 60, ...(token ? { [tokenKey]: token } : {}) }))
      out.push(...(p.Users ?? []).map(toUser))
      token = p[tokenKey]
      if (!token) break
    }
    return out
  }

  listUsers(): Promise<CognitoUser[]> { return this.paged('ListUsers', {}, 'PaginationToken') }

  async find(who: string): Promise<CognitoUser | null> {
    const attr = who.includes('@') ? 'email' : 'sub'
    if (!/^[^"\\\s]+$/.test(who)) return null
    const found = await this.paged('ListUsers', { Filter: `${attr} = "${who}"` }, 'PaginationToken')
    return found[0] ?? null
  }
  usersInGroup(group: string): Promise<CognitoUser[]> { return this.paged('ListUsersInGroup', { GroupName: group }, 'NextToken') }

  async createUser(email: string): Promise<CognitoUser> {
    const r = z.object({ User: UserShape }).loose().parse(await this.call('AdminCreateUser', {
      Username: email, DesiredDeliveryMediums: ['EMAIL'],
      UserAttributes: [{ Name: 'email', Value: email }, { Name: 'email_verified', Value: 'true' }],
    }))
    return toUser(r.User)
  }

  async groupsFor(username: string): Promise<string[]> {
    const Page = z.object({ Groups: z.array(z.object({ GroupName: z.string() }).loose()).optional(), NextToken: z.string().optional() }).loose()
    const out: string[] = []
    let token: string | undefined
    for (let i = 0; i < 20; i++) {
      const p = Page.parse(await this.call('AdminListGroupsForUser', { Username: username, Limit: 60, ...(token ? { NextToken: token } : {}) }))
      out.push(...(p.Groups ?? []).map((g) => g.GroupName))
      token = p.NextToken
      if (!token) break
    }
    return out
  }

  async addToGroup(username: string, group: string): Promise<void> { await this.call('AdminAddUserToGroup', { Username: username, GroupName: group }) }
  async removeFromGroup(username: string, group: string): Promise<void> { await this.call('AdminRemoveUserFromGroup', { Username: username, GroupName: group }) }
  async signOut(username: string): Promise<void> { await this.call('AdminUserGlobalSignOut', { Username: username }) }

  async createServiceClient(c: ServiceClientConfig): Promise<{ clientId: string; secret: string }> {
    this.checkNewName(c.clientName)
    const r = z.object({ UserPoolClient: z.object({ ClientId: z.string(), ClientSecret: z.string() }).loose() }).loose()
      .parse(await this.call('CreateUserPoolClient', { ...serviceClientBody(c), GenerateSecret: true }))
    this.made.add(r.UserPoolClient.ClientId)
    return { clientId: r.UserPoolClient.ClientId, secret: r.UserPoolClient.ClientSecret }
  }

  async updateServiceClient(clientId: string, c: ServiceClientConfig): Promise<void> {
    this.checkNewName(c.clientName)
    await this.checkService(clientId, c.clientName)
    await this.call('UpdateUserPoolClient', { ClientId: clientId, ...serviceClientBody(c) })
  }

  async deleteServiceClient(clientId: string): Promise<boolean> {
    if (!this.made.has(clientId)) await this.checkService(clientId)
    try {
      await this.call('DeleteUserPoolClient', { ClientId: clientId })
      this.made.delete(clientId)
      return true
    } catch (e) {
      if (e instanceof CognitoError && e.type === 'ResourceNotFoundException') return false
      throw e
    }
  }

  async addClientSecret(clientId: string): Promise<ClientSecret & { secret: string }> {
    await this.checkService(clientId)
    const r = z.object({ ClientSecretDescriptor: SecretShape.extend({ ClientSecretValue: z.string() }) }).loose()
      .parse(await this.call('AddUserPoolClientSecret', { ClientId: clientId }))
    return { ...toSecret(r.ClientSecretDescriptor), secret: r.ClientSecretDescriptor.ClientSecretValue }
  }

  async deleteClientSecret(clientId: string, secretId: string): Promise<void> {
    await this.checkService(clientId)
    await this.call('DeleteUserPoolClientSecret', { ClientId: clientId, ClientSecretId: secretId })
  }

  async listClientSecrets(clientId: string): Promise<ClientSecret[]> {
    await this.checkService(clientId)
    const Page = z.object({ ClientSecrets: z.array(SecretShape).optional(), NextToken: z.string().optional() }).loose()
    const out: ClientSecret[] = []
    let token: string | undefined
    for (let i = 0; i < 10; i++) {
      const p = Page.parse(await this.call('ListUserPoolClientSecrets', { ClientId: clientId, ...(token ? { NextToken: token } : {}) }))
      out.push(...(p.ClientSecrets ?? []).map(toSecret))
      token = p.NextToken
      if (!token) break
    }
    return out
  }
}

// ------------------------------------------------------------------ the GitHub token

let cached: { arn: string; token: string; at: number } | null = null

export async function githubToken(arn = process.env.TRACE_GITHUB_SECRET_ARN ?? ''): Promise<string> {
  if (process.env.TRACE_GITHUB_TOKEN) return process.env.TRACE_GITHUB_TOKEN
  if (!arn) throw new Error('TRACE_GITHUB_SECRET_ARN is not set')
  if (cached && cached.arn === arn && Date.now() - cached.at < 600_000) return cached.token
  const { GetSecretValueCommand, SecretsManagerClient } = await import('@aws-sdk/client-secrets-manager')
  const r = await new SecretsManagerClient({}).send(new GetSecretValueCommand({ SecretId: arn }))
  const token = (r.SecretString ?? '').trim()
  if (!token) throw new Error('the GitHub token secret is empty')
  cached = { arn, token, at: Date.now() }
  return token
}
