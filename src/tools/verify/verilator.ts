/**
 * Verilator: lint, build and run a testbench, with coverage.
 *
 *   lint   verilator --lint-only (default -Wall) over every source, top module given
 *   build  verilator --cc --exe --build: either the caller's C++ testbench (`cpp`), or, for a SystemVerilog/Verilog
 *          testbench (the top module drives itself, as under Icarus), a generated main() that runs the model to
 *          $finish with --timing and writes coverage.dat (Verilator 5.020's own --main does not write coverage)
 *   run    the built model, with plusargs; coverage.dat comes back, and `verilator_coverage --write-info` turns it into
 *          lcov's .info
 *
 * Pass or fail, in order: lint errors (warnings do not fail unless warnings_fail); the build failed; the model exited
 * non-zero or printed %Error / %Fatal ($error, $fatal, assertion failures); the output matched `fail`; `pass` was
 * given and never matched; a generated main() saw no $finish. Coverage kinds: line, toggle and branch are counted
 * per file (files matching coverage_exclude, testbenches by default, are left out of the percentages); user points
 * (cover property) and TRACE_COVER output lines become functional coverage hits in the project database.
 *
 * A C++ testbench that wants coverage writes it itself, to $TRACE_COVERAGE_FILE when set:
 *   contextp->coveragep()->write(getenv("TRACE_COVERAGE_FILE") ? getenv("TRACE_COVERAGE_FILE") : "coverage.dat");
 */
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { ToolError } from '../../core/registry.js'
import { coverLines, hdlStage, includeArgs, needProgram, shellJob, sq, stage } from './job.js'
import { parseCoverageDat, summarizeCoverage, verilatorMessages, type CovPoint, type VMessage } from './parse.js'

export interface VerilatorOptions {
  files: string[]
  top: string
  cpp?: string[] | undefined
  include_dirs?: string[] | undefined
  defines?: Record<string, string | number | boolean> | undefined
  parameters?: Record<string, string | number> | undefined
  mode: 'lint' | 'run'
  coverage: ('line' | 'toggle' | 'user')[]
  lint_flags: string[]
  build_flags: string[]
  plusargs: string[]
  pass?: string | undefined
  fail?: string | undefined
  warnings_fail: boolean
  coverage_exclude: string
  timeout_s: number
}

export interface VerilatorRun {
  passed: boolean
  reason: string
  stage: { lint: number | null; build: number | null; run: number | null }
  lint: VMessage[]
  build_errors: VMessage[]
  output: string
  lintLog: string
  buildLog: string
  coverageDat: string
  coverageInfo: string
  points: CovPoint[]
  functional: Map<string, { hits: number; location: string | null }>
  sources: string[]
  seconds: number
  where: string
}

export function mainCpp(top: string): string {
  const cls = `V${top}`
  return `// generated by trace verify.verilator: run ${top} to $finish and write coverage
#include "verilated.h"
#include "${cls}.h"
#include <cstdlib>
#include <memory>
int main(int argc, char** argv, char**) {
    const std::unique_ptr<VerilatedContext> contextp{new VerilatedContext};
    contextp->commandArgs(argc, argv);
    const std::unique_ptr<${cls}> topp{new ${cls}{contextp.get()}};
    while (!contextp->gotFinish()) {
        topp->eval();
        if (!topp->eventsPending()) break;
        contextp->time(topp->nextTimeSlot());
    }
    topp->final();
#if VM_COVERAGE
    const char* f = std::getenv("TRACE_COVERAGE_FILE");
    contextp->coveragep()->write(f && *f ? f : "coverage.dat");
#endif
    if (!contextp->gotFinish()) { VL_PRINTF("%%Warning: trace: the model stopped without $finish (no events left)\\n"); return 3; }
    return 0;
}
`
}

const defineArgs = (d: VerilatorOptions['defines']): string[] =>
  Object.entries(d ?? {}).filter(([, v]) => v !== false).map(([k, v]) => (v === true ? `+define+${k}` : `+define+${k}=${v}`))
const paramArgs = (p: VerilatorOptions['parameters']): string[] => Object.entries(p ?? {}).map(([k, v]) => `-G${k}=${v}`)

export async function runVerilator(o: VerilatorOptions): Promise<VerilatorRun> {
  needProgram('verilator', 'apt install verilator, or the OSS CAD Suite (github.com/YosysHQ/oss-cad-suite-build)')
  if (!/^[A-Za-z_][\w$]*$/.test(o.top)) throw new ToolError(`top ${JSON.stringify(o.top)} is not a module name`)
  if (!o.files.length) throw new ToolError('give files')
  // sources, include dirs and the C++ testbench keep their relative layout, so `include "sub/x.vh" resolves
  const st = hdlStage({ files: o.files, include_dirs: o.include_dirs, extra: o.cpp })
  const hdlNames = [...st.sources]
  const cppNames: string[] = [...st.extra]
  let tmp: string | null = null
  if (o.cpp?.length) {
    // given: staged above
  } else if (o.mode === 'run') {
    tmp = mkdtempSync(join(tmpdir(), 'trace-vmain-'))
    writeFileSync(join(tmp, 'trace_main.cpp'), mainCpp(o.top))
    stage([join(tmp, 'trace_main.cpp')], st)
    cppNames.push('trace_main.cpp')
  }
  const svTb = !o.cpp?.length
  const common = [...includeArgs(st), ...defineArgs(o.defines), ...paramArgs(o.parameters), '--top-module', o.top].map(sq).join(' ')
  const hdl = hdlNames.map((n) => `{in:${n}}`).join(' ')
  const cov = o.coverage.length === 3 ? ['--coverage'] : o.coverage.map((c) => `--coverage-${c}`)
  const lines = [
    'cd {dir}',
    `verilator --lint-only ${svTb ? '--timing ' : ''}${o.lint_flags.map(sq).join(' ')} ${common} ${hdl} > {out:lint.log} 2>&1`,
    'echo "lint=$?" > {out:status.txt}',
  ]
  if (o.mode === 'run') {
    lines.push(
      // the C++ build in parallel (--build-jobs), Verilator's own pass on one thread (--verilate-jobs 1): with -j N its
      // thread pool sometimes fails on the way out ("Internal Error: attempted to destroy locked Thread Pool"), more
      // often the more cores and the busier the machine, and the verilation of a testbench gains little from threads
      `verilator --cc --exe --build --build-jobs "$(nproc 2>/dev/null || echo 2)" --verilate-jobs 1 ${svTb ? '--timing ' : ''}-Wno-fatal ${cov.join(' ')} ${o.build_flags.map(sq).join(' ')} ${common} -Mdir obj -o trace_sim ${hdl} ${cppNames.map((n) => `{in:${n}}`).join(' ')} > {out:build.log} 2>&1`,
      'rc=$?; echo "build=$rc" >> {out:status.txt}',
      '[ "$rc" -eq 0 ] || exit 0',
      `TRACE_COVERAGE_FILE={dir}/coverage.dat ./obj/trace_sim ${o.plusargs.map((p) => sq(p.startsWith('+') ? p : `+${p}`)).join(' ')} > {out:sim.log} 2>&1`,
      'echo "run=$?" >> {out:status.txt}',
      'for f in {dir}/coverage.dat {dir}/logs/coverage.dat; do if [ -f "$f" ]; then cp "$f" {out:coverage.dat}; break; fi; done',
      'if [ -f {out:coverage.dat} ]; then verilator_coverage --write-info {out:coverage.info} {out:coverage.dat} > /dev/null 2>&1; fi',
    )
  }
  let r
  try {
    r = await shellJob({
      kind: 'verilator', script: lines.join('\n'), inputs: st.inputs, timeoutSeconds: o.timeout_s,
      outputs: ['status.txt', 'lint.log', 'build.log', 'sim.log', 'coverage.dat', 'coverage.info'],
    })
  } finally {
    if (tmp) rmSync(tmp, { recursive: true, force: true })
  }
  try {
    const status = Object.fromEntries([...r.text('status.txt').matchAll(/(\w+)=(-?\d+)/g)].map((m) => [m[1], Number(m[2])]))
    const stageRc = { lint: status.lint ?? null, build: status.build ?? null, run: status.run ?? null }
    const lintLog = r.text('lint.log')
    const buildLog = r.text('build.log')
    const output = r.text('sim.log')
    const lint = verilatorMessages(lintLog)
    const buildErrors = verilatorMessages(buildLog).filter((m) => m.severity === 'error')
    const coverageDat = r.text('coverage.dat')
    const points = coverageDat ? parseCoverageDat(coverageDat) : []
    const functional = new Map<string, { hits: number; location: string | null }>()
    for (const p of points.filter((q) => q.kind === 'user')) {
      const name = p.hier ? `${p.hier}.${p.comment}` : p.comment
      const cur = functional.get(name)
      functional.set(name, { hits: (cur?.hits ?? 0) + p.count, location: `${p.file}:${p.line}` })
    }
    for (const [n, h] of coverLines(output)) functional.set(n, { hits: (functional.get(n)?.hits ?? 0) + h, location: null })

    let passed = true
    let reason = o.mode === 'lint' ? 'lint clean' : 'finished'
    const lintErr = lint.filter((m) => m.severity === 'error')
    const lintWarn = lint.filter((m) => m.severity === 'warning')
    const fatal = /^.*%(Error|Fatal)\b.*$/m.exec(output)
    if (r.job.exitCode !== 0 && stageRc.lint === null) [passed, reason] = [false, `the job failed (exit ${r.job.exitCode}): ${(r.job.stderr || r.job.stdout).trim().split('\n').slice(-1)[0] ?? ''}`]
    else if (lintErr.length && (o.mode === 'lint' || stageRc.build !== 0)) [passed, reason] = [false, `lint: ${lintErr.length} error(s), first ${fmtMsg(lintErr[0] as VMessage)}`]
    else if (o.mode === 'lint' && o.warnings_fail && lintWarn.length) [passed, reason] = [false, `lint: ${lintWarn.length} warning(s), first ${fmtMsg(lintWarn[0] as VMessage)}`]
    else if (o.mode === 'lint' && stageRc.lint !== 0 && !lintWarn.length) [passed, reason] = [false, `verilator --lint-only exited ${stageRc.lint}: ${lintLog.trim().split('\n')[0] ?? ''}`]
    else if (o.mode === 'run') {
      if (stageRc.build !== 0) [passed, reason] = [false, `build failed${buildErrors[0] ? `: ${fmtMsg(buildErrors[0])}` : `: ${firstError(buildLog)}`}`]
      else if (fatal) [passed, reason] = [false, `the model reported: ${fatal[0].trim().slice(0, 300)}`]
      else if (o.fail && new RegExp(o.fail, 'm').test(output)) [passed, reason] = [false, `output matched the fail pattern: ${firstMatch(output, o.fail)}`]
      else if (stageRc.run === 3 && svTb) [passed, reason] = [false, 'the model stopped without $finish (no events left)']
      else if (stageRc.run !== 0) [passed, reason] = [false, `the model exited ${stageRc.run}${r.job.exitCode === 137 || stageRc.run === null ? ' (killed: time limit?)' : ''}`]
      else if (o.pass) {
        if (new RegExp(o.pass, 'm').test(output)) reason = `output matched the pass pattern: ${firstMatch(output, o.pass)}`
        else [passed, reason] = [false, 'the pass pattern never appeared in the output']
      }
      if (passed && lintWarn.length && o.warnings_fail) [passed, reason] = [false, `lint: ${lintWarn.length} warning(s), first ${fmtMsg(lintWarn[0] as VMessage)}`]
    }
    return {
      passed, reason, stage: stageRc, lint, build_errors: buildErrors, output, lintLog, buildLog, coverageDat, coverageInfo: r.text('coverage.info'),
      points, functional, sources: hdlNames, seconds: r.job.seconds, where: r.job.where,
    }
  } finally {
    r.cleanup()
  }
}

export function coverageSummary(points: readonly CovPoint[], exclude: string): ReturnType<typeof summarizeCoverage> {
  return summarizeCoverage(points.filter((p) => p.kind !== 'user'), exclude ? { exclude: new RegExp(exclude) } : {})
}

const fmtMsg = (m: VMessage): string => `${m.code ? `${m.code} ` : ''}${m.file ? `${m.file.split('/').pop()}:${m.line}: ` : ''}${m.text}`.slice(0, 300)

function firstError(log: string): string {
  const lines = log.split('\n').map((l) => l.trim()).filter(Boolean)
  return (lines.find((l) => /error/i.test(l)) ?? lines[lines.length - 1] ?? '(no output)').slice(0, 300)
}

function firstMatch(text: string, re: string): string {
  const m = new RegExp(`^.*(?:${re}).*$`, 'm').exec(text)
  return (m?.[0] ?? '').trim().slice(0, 200)
}
