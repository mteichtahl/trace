/**
 * cocotb: run Python testbenches against an HDL design on Icarus Verilog or Verilator, through cocotb's own runner
 * (cocotb_tools.runner in cocotb 2.x, cocotb.runner in 1.8/1.9), and read its results.xml.
 *
 * The job runs a small driver script (written here, sent as an input) with the job's Python: TRACE_COCOTB_PYTHON when
 * set, else python3. The driver builds the design (sources, include dir, defines, parameters), runs the test modules
 * (optionally only some test cases) and copies the waveform out when asked. Arguments the installed runner does not
 * accept are left out (the runner's signature differs between cocotb versions). Each test case's verdict comes from
 * results.xml; TRACE_COVER lines in the output become functional coverage hits.
 *
 * Verilator under cocotb needs the Verilator version that cocotb release supports (cocotb 2.x: 5.036 or later); the
 * runner reports an older one as an error, which is returned as such.
 */
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { ToolError } from '../../core/registry.js'
import { coverLines, includeFiles, needProgram, shellJob, sq, stage } from './job.js'
import { parseCocotbResults, type CocotbCase } from './parse.js'

export const DRIVER = String.raw`# generated by trace verify.cocotb
import glob, inspect, json, os, shutil, sys
d, results, waves_out = sys.argv[1], sys.argv[2], sys.argv[3]
spec = json.loads(os.environ["TRACE_COCOTB_SPEC"])
inp = os.path.join(d, "in")
sys.path.insert(0, inp)
try:
    from cocotb_tools.runner import get_runner
except ImportError:
    from cocotb.runner import get_runner
import cocotb
print("TRACE_COCOTB_VERSION " + getattr(cocotb, "__version__", "?"), flush=True)

def call(fn, **kw):
    sig = inspect.signature(fn).parameters
    return fn(**{k: v for k, v in kw.items() if k in sig and v is not None})

runner = get_runner(spec["simulator"])
build_dir = os.path.join(d, "build")
call(runner.build,
     sources=[os.path.join(inp, n) for n in spec["sources"]],
     verilog_sources=None,
     hdl_toplevel=spec["top"],
     build_dir=build_dir,
     always=True,
     includes=[inp],
     defines=spec["defines"],
     parameters=spec["parameters"],
     build_args=spec["build_args"],
     timescale=tuple(spec["timescale"]) if spec["timescale"] else None,
     waves=spec["waves"] or None)
env = dict(spec["env"])
env["PYTHONPATH"] = inp + os.pathsep + os.environ.get("PYTHONPATH", "")
filt = spec["testcase"] or None
sig = inspect.signature(runner.test).parameters
kw = dict(hdl_toplevel=spec["top"], test_module=spec["modules"], build_dir=build_dir, test_dir=inp,
          results_xml=results, extra_env=env, plusargs=spec["plusargs"], waves=spec["waves"] or None,
          seed=spec["seed"])
if filt:
    if "test_filter" in sig:
        kw["test_filter"] = "|".join("^%s$" % t for t in filt)
    else:
        kw["testcase"] = filt
call(runner.test, **kw)
if spec["waves"]:
    found = sorted(glob.glob(os.path.join(build_dir, "**", "*.fst"), recursive=True) + glob.glob(os.path.join(build_dir, "**", "*.vcd"), recursive=True))
    if found:
        shutil.copyfile(found[0], waves_out)
        print("TRACE_COCOTB_WAVES " + os.path.basename(found[0]), flush=True)
`

export interface CocotbOptions {
  files: string[]
  top: string
  modules: string[]
  simulator: 'icarus' | 'verilator'
  include_dirs?: string[] | undefined
  defines?: Record<string, string | number | boolean> | undefined
  parameters?: Record<string, string | number> | undefined
  testcase?: string[] | undefined
  plusargs: string[]
  env: Record<string, string>
  build_args: string[]
  timescale?: [string, string] | undefined
  seed?: number | undefined
  waves: boolean
  timeout_s: number
}

export interface CocotbRun {
  passed: boolean
  reason: string
  cases: CocotbCase[]
  output: string
  resultsXml: string
  waves: Uint8Array | null
  wavesName: string | null
  cocotbVersion: string | null
  functional: Map<string, { hits: number; location: string | null }>
  seconds: number
  where: string
}

const python = (): string => process.env.TRACE_COCOTB_PYTHON || 'python3'

export async function runCocotb(o: CocotbOptions): Promise<CocotbRun> {
  needProgram('cocotb-config', 'pip install cocotb (and set TRACE_COCOTB_PYTHON to the Python it is installed in)', 'TRACE_COCOTB_CONFIG')
  needProgram(o.simulator === 'icarus' ? 'iverilog' : 'verilator', o.simulator === 'icarus' ? 'apt install iverilog' : 'apt install verilator')
  if (!o.files.length) throw new ToolError('give files (the HDL sources)')
  if (!o.modules.length) throw new ToolError('give modules (the Python test files)')
  const st = stage(o.files)
  const hdl = [...st.names]
  stage(includeFiles(o.include_dirs ?? []), st)
  const before = st.names.length
  stage(o.modules, st)
  const mods = st.names.slice(before).map((n) => {
    if (!/\.py$/.test(n)) throw new ToolError(`${n}: test modules are Python files`)
    return n.replace(/\.py$/, '')
  })
  const tmp = mkdtempSync(join(tmpdir(), 'trace-cocotb-'))
  writeFileSync(join(tmp, 'trace_cocotb_driver.py'), DRIVER)
  stage([join(tmp, 'trace_cocotb_driver.py')], st)
  const spec = {
    simulator: o.simulator, top: o.top, sources: hdl, modules: mods,
    defines: Object.fromEntries(Object.entries(o.defines ?? {}).filter(([, v]) => v !== false).map(([k, v]) => [k, v === true ? 1 : v])),
    parameters: o.parameters ?? {}, build_args: o.build_args, plusargs: o.plusargs, env: o.env, testcase: o.testcase ?? [],
    timescale: o.timescale ?? null, seed: o.seed ?? null, waves: o.waves,
  }
  let r
  try {
    r = await shellJob({
      kind: 'cocotb', timeoutSeconds: o.timeout_s, inputs: st.inputs,
      script: `cd {dir}\n${sq(python())} {in:trace_cocotb_driver.py} {dir} {out:results.xml} {out:waves.bin} > {out:cocotb.log} 2>&1\necho "rc=$?" > {out:status.txt}`,
      outputs: ['results.xml', 'waves.bin', 'cocotb.log', 'status.txt'],
      env: { TRACE_COCOTB_SPEC: JSON.stringify(spec), COCOTB_ANSI_OUTPUT: '0', NO_COLOR: '1' },
    })
  } finally {
    rmSync(tmp, { recursive: true, force: true })
  }
  try {
    const output = r.text('cocotb.log')
    const rc = Number(/rc=(-?\d+)/.exec(r.text('status.txt'))?.[1] ?? NaN)
    const xml = r.text('results.xml')
    let cases: CocotbCase[] = []
    let reason = ''
    if (xml.trim()) {
      try {
        cases = parseCocotbResults(xml)
      } catch (e) {
        reason = `results.xml is unreadable: ${e instanceof Error ? e.message : String(e)}`
      }
    }
    const failed = cases.filter((c) => c.status === 'fail' || c.status === 'error')
    let passed = false
    if (reason) passed = false
    else if (!xml.trim()) reason = `cocotb wrote no results (exit ${Number.isNaN(rc) ? r.job.exitCode : rc}): ${lastError(output)}`
    else if (!cases.length) reason = 'no test cases ran (check modules and testcase)'
    else if (failed.length) reason = `${failed.length} of ${cases.length} failed: ${failed.slice(0, 3).map((c) => `${c.name}${c.message ? ` (${c.message.split('\n')[0]?.slice(0, 120)})` : ''}`).join('; ')}`
    else {
      passed = true
      const skipped = cases.filter((c) => c.status === 'skip').length
      reason = `${cases.length - skipped} passed${skipped ? `, ${skipped} skipped` : ''}`
    }
    const functional = new Map<string, { hits: number; location: string | null }>()
    for (const [n, h] of coverLines(output)) functional.set(n, { hits: h, location: null })
    const wavesName = /TRACE_COCOTB_WAVES (\S+)/.exec(output)?.[1] ?? null
    return {
      passed, reason, cases, output, resultsXml: xml, waves: r.bytes('waves.bin'), wavesName,
      cocotbVersion: /TRACE_COCOTB_VERSION (\S+)/.exec(output)?.[1] ?? null, functional, seconds: r.job.seconds, where: r.job.where,
    }
  } finally {
    r.cleanup()
  }
}

function lastError(log: string): string {
  const lines = log.split('\n').map((l) => l.trim()).filter(Boolean)
  return (lines.reverse().find((l) => /error|exception|not found|unsupported|requires/i.test(l)) ?? lines[0] ?? '(no output)').slice(0, 300)
}
